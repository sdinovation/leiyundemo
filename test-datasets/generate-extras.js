// 生成 finance.csv / dirty_data.csv / leap_year.csv
const fs = require('fs');
const path = require('path');

// ============ finance.csv ============
// 24 行：12 个月财务数据 × 2 年（含同比/环比/百分比/汇率 + 2 个币种）
// 月份用 ISO 日期格式（YYYY-MM-01）以便现有日期解析器识别
// 币种按奇偶月分配：奇数月 USD / 偶数月 EUR，避免 GROUP BY 币种 退化为 1 行
const FIN = path.join(__dirname, 'finance.csv');
const fin = ['日期,营收,成本,毛利率,汇率,币种'];
const months2024 = ['2024-01', '2024-02', '2024-03', '2024-04', '2024-05', '2024-06', '2024-07', '2024-08', '2024-09', '2024-10', '2024-11', '2024-12'];
const months2025 = months2024.map(m => m.replace('2024', '2025'));
months2024.forEach((m, i) => {
  const rev = 80000 + i * 5000;
  const cost = rev * 0.6;
  const margin = ((rev - cost) / rev * 100).toFixed(1);
  const rate = (7.1 + i * 0.01).toFixed(2);
  const ccy = i % 2 === 0 ? 'USD' : 'EUR';
  fin.push(`${m}-01,${rev},${cost.toFixed(0)},${margin},${rate},${ccy}`);
});
months2025.forEach((m, i) => {
  const rev = 150000 + i * 7000;
  const cost = rev * 0.55;
  const margin = ((rev - cost) / rev * 100).toFixed(1);
  const rate = (7.2 + i * 0.005).toFixed(2);
  const ccy = i % 2 === 0 ? 'USD' : 'EUR';
  fin.push(`${m}-01,${rev},${cost.toFixed(0)},${margin},${rate},${ccy}`);
});
fs.writeFileSync(FIN, fin.join('\n'), 'utf-8');
console.log(`finance.csv: ${fin.length - 1} 行 (2 币种)`);

